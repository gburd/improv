#!/usr/bin/env bash
# The Homebrew formula for a release, from its macOS tarballs' SHA256SUMS:
#   ci/homebrew-formula.sh vX.Y.Z SHA256SUMS > improv.rb
# A tap (a repository named homebrew-<tap>) serves it: `brew install
# gburd/improv/improv` reads Formula/improv.rb from gburd/homebrew-improv.
set -euo pipefail
tag=$1 sums=$2
sum() { awk -v f="improv-$tag-$1.tar.gz" '$2 == f { print $1 }' "$sums" | grep -E '^[0-9a-f]{64}$'; }
# Separate assignments: in one `a=$(..) b=$(..)` only the last failure counts.
arm=$(sum aarch64-apple-darwin)
intel=$(sum x86_64-apple-darwin)
url=https://github.com/gburd/improv/releases/download/$tag
cat <<RB
# Generated by ci/homebrew-formula.sh from the $tag release; do not edit.
class Improv < Formula
  desc "Multidimensional spreadsheet (Lotus Improv lineage): CLI, TUI, server, GUI"
  homepage "https://codeberg.org/gregburd/improv"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "$url/improv-$tag-aarch64-apple-darwin.tar.gz"
      sha256 "$arm"
    end
    on_intel do
      url "$url/improv-$tag-x86_64-apple-darwin.tar.gz"
      sha256 "$intel"
    end
  end

  def install
    bin.install "improv", "improv-tui", "improv-server", "improv-gui"
    man1.install Dir["man/man1/*"]
    man5.install Dir["man/man5/*"]
    man7.install Dir["man/man7/*"]
    bash_completion.install "completions/bash/improv.bash" => "improv"
    zsh_completion.install "completions/zsh/_improv"
    fish_completion.install "completions/fish/improv.fish"
  end

  test do
    assert_equal "improv #{version}", shell_output("#{bin}/improv --version").strip
    system bin/"improv", "init", testpath/"m.db"
  end
end
RB
